// one regex for underlining terms in lesson text. Everyday words that are
// also glossary terms are left out so ordinary sentences don't light up.
const NO_AUTO = new Set(['Set', 'Base', 'Unit', 'Root', 'Current', 'Force', 'Limit', 'Function', 'Factor', 'Phase', 'Variable', 'Equation', 'Elastic', 'Crystal', 'Element', 'Compound', 'Atom', 'Ratio', 'Fraction', 'Decimal', 'Exponent']);
const words = GLOSSARY.flatMap((g) => (NO_AUTO.has(g.term) ? [] : [g.term, ...g.match]).filter((w) => w.length > 3 || /^[A-Z]{3}$/.test(w)).map((w) => ({ w, g })));
words.sort((a, b) => b.w.length - a.w.length);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
export const GLOSS_LOOKUP = new Map(words.map(({ w, g }) => [w.toLowerCase(), g]));
export const GLOSS_RE = new RegExp(`(?<![\\p{L}\\p{N}])(${words.map(({ w }) => esc(w)).join('|')})(?![\\p{L}\\p{N}])`, 'giu');
